# ── Unity GUID generation ─────────────────────────────────────────────────────

def _unity_guid(name: str) -> str:
    """Generate a deterministic Unity-style GUID from a name string."""
    h = hashlib.md5(name.encode("utf-8")).hexdigest()
    return h  # 32-char hex = valid Unity GUID


# ── Workspace ─────────────────────────────────────────────────────────────────

def _workspace(project_name: str) -> Path:
    root = Path(
        os.environ.get("REMIRDY_WORKSPACE", str(Path.home() / "RemirdyWorkspace"))
    ) / "outputs" / "unity" / project_name
    root.mkdir(parents=True, exist_ok=True)
    return root


# ── .meta file generator ──────────────────────────────────────────────────────

def _make_meta(asset_path: Path, guid: str) -> str:
    ext = asset_path.suffix.lower()
    if ext in (".glb", ".fbx", ".obj"):
        return f"""fileFormatVersion: 2
guid: {guid}
ModelImporter:
  serializedVersion: 21300
  internalIDToNameTable: []
  externalObjects: {{}}
  materials:
    materialImportMode: 2
    materialName: 0
    materialSearch: 1
    materialLocation: 1
  animations:
    legacyGenerateAnimations: 4
    bakeSimulation: 0
    resampleCurves: 1
    optimizeGameObjects: 0
  importConstraints: 0
  importAnimation: 1
  humanDescription:
    serializedVersion: 3
    human: []
    skeleton: []
  userData:
  assetBundleName:
  assetBundleVariant:
"""
    if ext == ".png":
        return f"""fileFormatVersion: 2
guid: {guid}
TextureImporter:
  serializedVersion: 12
  mipmaps:
    mipMapMode: 0
    enableMipMap: 1
    sRGBTexture: 1
    linearTexture: 0
  textureType: 0
  textureShape: 1
  singleChannelComponent: 0
  flipbookRows: 1
  flipbookColumns: 1
  userData:
  assetBundleName:
  assetBundleVariant:
"""
    if ext in (".cs",):
        return f"""fileFormatVersion: 2
guid: {guid}
MonoImporter:
  externalObjects: {{}}
  serializedVersion: 2
  defaultReferences: []
  executionOrder: 0
  icon: {{instanceID: 0}}
  userData:
  assetBundleName:
  assetBundleVariant:
"""
    return f"fileFormatVersion: 2\nguid: {guid}\nDefaultImporter:\n  externalObjects: {{}}\n  userData:\n"


# ── C# script templates ───────────────────────────────────────────────────────

def _csharp_interactable(obj_name: str) -> str:
    class_name = "".join(w.capitalize() for w in obj_name.split("_")[:3])
    return f"""using UnityEngine;

/// <summary>
/// Auto-generated by Remirdy Blender Studio MCP.
/// Object: {obj_name}
/// </summary>
[RequireComponent(typeof(Collider))]
public class {class_name}Interactable : MonoBehaviour
{{
    [Header("Interaction Settings")]
    public bool isInteractable = true;
    public string displayName = "{obj_name}";
    public float interactionRadius = 2f;

    private void OnMouseEnter()
    {{
        if (isInteractable)
            Debug.Log($"[{{displayName}}] Player is nearby.");
    }}

    private void OnMouseDown()
    {{
        if (isInteractable)
            OnInteract();
    }}

    public virtual void OnInteract()
    {{
        Debug.Log($"[{{displayName}}] Interacted!");
        // TODO: Add interaction logic here
    }}
}}
"""


def _csharp_npc(obj_name: str) -> str:
    class_name = "".join(w.capitalize() for w in obj_name.split("_")[:3])
    return f"""using UnityEngine;
using UnityEngine.AI;

/// <summary>
/// Auto-generated NPC controller by Remirdy Blender Studio MCP.
/// Object: {obj_name}
/// </summary>
[RequireComponent(typeof(NavMeshAgent))]
[RequireComponent(typeof(Animator))]
public class {class_name}NPC : MonoBehaviour
{{
    [Header("NPC Settings")]
    public float walkSpeed = 2f;
    public float idleTime = 3f;
    public Transform[] patrolPoints;

    private NavMeshAgent _agent;
    private Animator _animator;
    private int _currentPatrolIndex = 0;
    private float _idleTimer = 0f;
    private bool _isIdle = false;

    void Start()
    {{
        _agent = GetComponent<NavMeshAgent>();
        _animator = GetComponent<Animator>();
        _agent.speed = walkSpeed;
        MoveToNextPatrolPoint();
    }}

    void Update()
    {{
        if (_isIdle)
        {{
            _idleTimer -= Time.deltaTime;
            if (_idleTimer <= 0f)
            {{
                _isIdle = false;
                MoveToNextPatrolPoint();
            }}
            return;
        }}

        if (!_agent.pathPending && _agent.remainingDistance < 0.5f)
        {{
            _isIdle = true;
            _idleTimer = idleTime;
            _animator?.SetBool("IsWalking", false);
        }}
    }}

    void MoveToNextPatrolPoint()
    {{
        if (patrolPoints == null || patrolPoints.Length == 0) return;
        _agent.destination = patrolPoints[_currentPatrolIndex].position;
        _currentPatrolIndex = (_currentPatrolIndex + 1) % patrolPoints.Length;
        _animator?.SetBool("IsWalking", true);
    }}
}}
"""


def _csharp_environment_manager(project_name: str, objects: list[str]) -> str:
    return f"""using UnityEngine;
using System.Collections.Generic;

/// <summary>
/// Auto-generated Environment Manager by Remirdy Blender Studio MCP.
/// Project: {project_name}
/// Scene objects: {', '.join(objects[:10])}
/// </summary>
public class EnvironmentManager : MonoBehaviour
{{
    public static EnvironmentManager Instance {{ get; private set; }}

    [Header("Scene References")]
    public Light mainDirectionalLight;
    public ReflectionProbe reflectionProbe;

    [Header("Day/Night Cycle")]
    public bool enableDayNightCycle = false;
    public float dayDurationSeconds = 120f;
    [Range(0, 1)] public float timeOfDay = 0.5f;  // 0 = midnight, 0.5 = noon

    private void Awake()
    {{
        if (Instance != null) {{ Destroy(gameObject); return; }}
        Instance = this;
        DontDestroyOnLoad(gameObject);
    }}

    private void Update()
    {{
        if (!enableDayNightCycle || mainDirectionalLight == null) return;
        timeOfDay = (timeOfDay + Time.deltaTime / dayDurationSeconds) % 1f;
        float sunAngle = timeOfDay * 360f - 90f;
        mainDirectionalLight.transform.rotation = Quaternion.Euler(sunAngle, -30f, 0f);
        mainDirectionalLight.intensity = Mathf.Clamp01(Mathf.Sin(timeOfDay * Mathf.PI)) * 1.5f;
    }}

    public void SetTimeOfDay(float t) => timeOfDay = Mathf.Clamp01(t);
}}
"""


# ── Unity scene file (.unity) ─────────────────────────────────────────────────

def _make_unity_scene(objects: list[dict[str, Any]], project_name: str) -> str:
    """Generate a minimal Unity YAML scene file."""
    lines = [
        "%YAML 1.1",
        "%TAG !u! tag:unity3d.com,2011:",
        "--- !u!29 &1",
        "OcclusionCullingSettings:",
        "  m_ObjectHideFlags: 0",
        "  serializedVersion: 2",
        "  m_OcclusionBakeSettings:",
        "    smallestOccluder: 5",
        "    smallestHole: 0.25",
        "    backfaceThreshold: 100",
        "--- !u!104 &2",
        "RenderSettings:",
        "  m_ObjectHideFlags: 0",
        "  serializedVersion: 9",
        "  m_Fog: 0",
        "  m_FogColor: {r: 0.5, g: 0.5, b: 0.5, a: 1}",
        "  m_AmbientMode: 0",
        "  m_AmbientSkyColor: {r: 0.212, g: 0.227, b: 0.259, a: 1}",
        "  m_SkyboxMaterial: {fileID: 0}",
        "  m_Sun: {fileID: 0}",
    ]

    for i, obj in enumerate(objects[:20]):
        game_obj_id = 100 + i * 10
        name = obj.get("name", f"Object_{i}")
        loc = obj.get("location", [0, 0, 0])
        lines += [
            f"--- !u!1 &{game_obj_id}",
            "GameObject:",
            "  m_ObjectHideFlags: 0",
            f"  m_Name: {name}",
            "  m_IsActive: 1",
            f"--- !u!4 &{game_obj_id + 1}",
            "Transform:",
            f"  m_GameObject: {{fileID: {game_obj_id}}}",
            f"  m_LocalPosition: {{x: {loc[0]:.3f}, y: {loc[2]:.3f}, z: {loc[1]:.3f}}}",
            "  m_LocalRotation: {x: 0, y: 0, z: 0, w: 1}",
            "  m_LocalScale: {x: 1, y: 1, z: 1}",
        ]

    return "\n".join(lines)


# ── Full package builder ──────────────────────────────────────────────────────

def build_unity_package(
    project_name: str,
    glb_paths: list[str],
    scene_graph: dict,
    generate_scripts: bool = True,
    generate_scene_file: bool = True,
) -> dict[str, Any]:
    """
    Build a complete .unitypackage from Blender export files.
    """
    workspace = _workspace(project_name)
    assets_dir = workspace / "Assets" / project_name
    scripts_dir = assets_dir / "Scripts"
    models_dir  = assets_dir / "Models"
    textures_dir = assets_dir / "Textures"
    scenes_dir  = assets_dir / "Scenes"

    for d in (assets_dir, scripts_dir, models_dir, textures_dir, scenes_dir):
        d.mkdir(parents=True, exist_ok=True)

    created_files: list[str] = []
    guids: dict[str, str] = {}

    # Copy GLB files + generate .meta
    for glb in glb_paths:
        p = Path(glb)
        if not p.exists():
            continue
        dest = models_dir / p.name
        shutil.copy2(p, dest)
        guid = _unity_guid(str(dest))
        guids[p.name] = guid
        (dest.with_suffix(dest.suffix + ".meta")).write_text(_make_meta(dest, guid))
        created_files.append(str(dest))

    objects = scene_graph.get("objects", [])
    obj_names = [o.get("name", "") for o in objects if o.get("type") == "MESH"]

    # Generate C# scripts
    if generate_scripts:
        # Environment manager
        env_script = scripts_dir / "EnvironmentManager.cs"
        env_script.write_text(_csharp_environment_manager(project_name, obj_names))
        guid_env = _unity_guid(str(env_script))
        (env_script.with_suffix(".cs.meta")).write_text(_make_meta(env_script, guid_env))
        created_files.append(str(env_script))

        # Per-object scripts (characters get NPC, props get Interactable)
        for obj in objects[:10]:
            name = obj.get("name", "")
            name_lower = name.lower()
            if any(k in name_lower for k in ("chr_", "character", "npc", "humanoid")):
                script_path = scripts_dir / f"{name}NPC.cs"
                script_path.write_text(_csharp_npc(name))
            elif any(k in name_lower for k in ("prop_", "chest", "door", "item", "pickup")):
                script_path = scripts_dir / f"{name}Interactable.cs"
                script_path.write_text(_csharp_interactable(name))
            else:
                continue
            guid_s = _unity_guid(str(script_path))
            (script_path.with_suffix(script_path.suffix + ".meta")).write_text(
                _make_meta(script_path, guid_s)
            )
            created_files.append(str(script_path))

    # Generate Unity scene file
    scene_path = None
    if generate_scene_file:
        scene_path = scenes_dir / f"{project_name}.unity"
        scene_path.write_text(_make_unity_scene(objects, project_name))
        guid_scene = _unity_guid(str(scene_path))
        (scenes_dir / f"{project_name}.unity.meta").write_text(_make_meta(scene_path, guid_scene))
        created_files.append(str(scene_path))

    # NavMesh hints file
    navmesh_note = assets_dir / "NAVMESH_HINTS.txt"
    walkable = [o.get("name") for o in objects if any(
        k in o.get("name", "").lower() for k in ("ground", "floor", "terrain", "road", "path")
    )]
    obstacle = [o.get("name") for o in objects if any(
        k in o.get("name", "").lower() for k in ("wall", "rock", "tree", "building", "obstacle")
    )]
    navmesh_note.write_text(
        f"NavMesh Bake Hints — {project_name}\n"
        f"Walkable surfaces: {', '.join(walkable) or 'none detected'}\n"
        f"Obstacles/Static: {', '.join(obstacle) or 'none detected'}\n"
        f"Bake NavMesh via: Window > AI > Navigation > Bake\n"
    )

    # Pack into .unitypackage (ZIP format)
    pkg_path = workspace / f"{project_name}.unitypackage"
    with zipfile.ZipFile(pkg_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in workspace.rglob("*"):
            if f.is_file():
                zf.write(f, f.relative_to(workspace))

    return {
        "ok": True,
        "project_name": project_name,
        "package_path": str(pkg_path),
        "workspace": str(workspace),
        "assets_dir": str(assets_dir),
        "scripts_generated": len([f for f in created_files if f.endswith(".cs")]),
        "models_included": len(glb_paths),
        "scene_file": str(scene_path) if scene_path else None,
        "navmesh_hints": str(navmesh_note),
        "total_files": len(created_files),
        "guids": guids,
        "import_instructions": (
            f"Open Unity → Assets → Import Package → Custom Package → "
            f"select '{project_name}.unitypackage'"
        ),
    }


# ── MCP tool registration ─────────────────────────────────────────────────────

def register(mcp: FastMCP) -> None:

    @mcp.tool()
    def export_complete_unity_project(
        project_name: str = "RemirdyScene",
        generate_scripts: bool = True,
        generate_scene_file: bool = True,
        apply_transforms: bool = True,
    ) -> dict:
        """
        Export the current Blender scene as a complete Unity project package.

        Goes far beyond simple GLB export:
          • .unitypackage with proper Assets folder structure
          • .meta files with deterministic GUIDs for every asset
          • Auto-generated C# MonoBehaviour scripts per object role:
              - Characters → NPC controller (NavMeshAgent + Animator + patrol)
              - Props → Interactable (OnMouseDown, interaction radius)
              - Scene → EnvironmentManager (day/night cycle, lighting)
          • NavMesh bake hints (walkable/obstacle surface list)
          • Unity YAML scene file (.unity) with pre-placed objects
          • Import instructions included

        Args:
            project_name      : Unity project/package name (default RemirdyScene).
            generate_scripts  : Generate C# scripts per object role (default True).
            generate_scene_file: Generate .unity scene file (default True).
            apply_transforms  : Apply scale/rotation before export (default True).
        """
        # 1. Prepare for Unity (scale, coordinate system)
        prep_result = call("prepare_for_unity_export", {"apply_transforms": apply_transforms})

        # 2. Export GLB
        import os, time
        from pathlib import Path
        root = Path(os.environ.get("REMIRDY_WORKSPACE", str(Path.home() / "RemirdyWorkspace")))
        glb_path = str(root / "outputs" / "exports" / f"{project_name}.glb")

        export_result = call("export_glb", {"filename": f"{project_name}.glb", "output_path": glb_path})
        actual_glb = export_result.get("export_path") or glb_path

        # 3. Get scene graph for metadata
        graph = call("get_scene_graph", {})
        scene_graph = graph if graph.get("ok") else {"objects": []}

        # 4. Build Unity package
        pkg = build_unity_package(
            project_name=project_name,
            glb_paths=[actual_glb],
            scene_graph=scene_graph,
            generate_scripts=generate_scripts,
            generate_scene_file=generate_scene_file,
        )

        return {
            **pkg,
            "blender_prep": prep_result,
            "glb_export": export_result,
        }

    @mcp.tool()
    def generate_unity_scripts_for_scene(project_name: str = "RemirdyScene") -> dict:
        """
        Generate C# Unity scripts for the current scene objects without re-exporting the model.
        Useful when you've already exported the GLB and just need the scripts.

        Generates:
          - EnvironmentManager.cs (lighting, day/night cycle)
          - {ObjectName}NPC.cs for character objects (NavMesh patrol AI)
          - {ObjectName}Interactable.cs for prop objects (click interaction)
        """
        graph = call("get_scene_graph", {})
        scene_graph = graph if graph.get("ok") else {"objects": []}

        workspace = _workspace(project_name)
        scripts_dir = workspace / "Assets" / project_name / "Scripts"
        scripts_dir.mkdir(parents=True, exist_ok=True)

        objects = scene_graph.get("objects", [])
        obj_names = [o.get("name", "") for o in objects if o.get("type") == "MESH"]
        generated = []

        env_script = scripts_dir / "EnvironmentManager.cs"
        env_script.write_text(_csharp_environment_manager(project_name, obj_names))
        generated.append("EnvironmentManager.cs")

        for obj in objects[:15]:
            name = obj.get("name", "")
            nlow = name.lower()
            if any(k in nlow for k in ("chr_", "character", "npc", "humanoid", "player")):
                p = scripts_dir / f"{name}NPC.cs"
                p.write_text(_csharp_npc(name))
                generated.append(p.name)
            elif any(k in nlow for k in ("prop_", "chest", "door", "item", "pickup", "collectible")):
                p = scripts_dir / f"{name}Interactable.cs"
                p.write_text(_csharp_interactable(name))
                generated.append(p.name)

        return {
            "ok": True,
            "project_name": project_name,
            "scripts_dir": str(scripts_dir),
            "scripts_generated": generated,
            "count": len(generated),
        }

    @mcp.tool()
    def prepare_and_export_for_unity(
        filename: str = "scene",
        scale_factor: float = 1.0,
    ) -> dict:
        """
        Quick Unity export: apply transforms + coordinate fix + GLB export.
        (Use export_complete_unity_project for the full package with scripts.)

        Args:
            filename     : Output filename (without extension).
            scale_factor : Unity scale multiplier (default 1.0 = metres).
        """
        prep = call("prepare_for_unity_export", {"apply_transforms": True})
        export = call("export_glb", {"filename": f"{filename}_unity.glb"})
        return {
            "ok": True,
            "preparation": prep,
            "export": export,
            "unity_scale": scale_factor,
            "coordinate_convention": "Y-up (Unity standard)",
            "next_step": "Drag the GLB into your Unity project Assets folder.",
        }
